#!/usr/bin/env python3
"""Generate the OpenCASCADE (OCCT) part of toolchains/third_party/ANUBIS.

Not part of the build. OCCT describes itself in plain text files, which this
script turns into one cc_static_library per toolkit:
  src/<TK>/PACKAGES   the packages in a toolkit
  src/<TK>/EXTERNLIB  toolkits (TK*) and system libraries (CSF_*) it uses
  src/<Pkg>/FILES     a package's sources and headers

Headers are included by bare name (#include <Standard.hxx>), so each toolkit
exports its package directories as include dirs. Flags match what OCCT's
CMake sets for a static Release build (adm/cmake/occt_defs_flags.cmake).

Usage: occt_to_anubis.py <occt src dir> > generated block
Run from the superdex root with the Natron-installed sources:
  tools/anubis/occt_to_anubis.py toolchains/third_party/occt
"""
import sys
from pathlib import Path

# superdex_mesh_cli's toolkit set (superdex_mesh_cli/CMakeLists.txt) and what
# EXTERNLIB pulls in.
ROOTS = ["TKDESTEP", "TKMesh", "TKBO", "TKShHealing", "TKTopAlgo", "TKGeomBase", "TKG3d", "TKBRep",
         "TKMath", "TKernel", "TKXCAF", "TKLCAF", "TKCAF", "TKRWMesh", "TKDEGLTF", "TKDEOBJ", "TKDESTL"]

# Header-only uses EXTERNLIB leaves out (OCCT's CMake installs every header into
# one directory, so it never notices): Transfer includes DE_ShapeFixParameters.hxx.
EXTRA_DEPS = {"TKXSBase": ["TKDE"]}

# CSF_* names from EXTERNLIB -> (linux libraries, windows libraries).
# Linux pthread/dl come with the zig_glibc libc every Linux binary links.
CSF = {
    "CSF_ThreadLibs": ([], []),
    "CSF_dl": ([], []),
    "CSF_advapi32": ([], ["advapi32"]),
    "CSF_gdi32": ([], ["gdi32"]),
    "CSF_user32": ([], ["user32"]),
    "CSF_wsock32": ([], ["wsock32"]),
    "CSF_psapi": ([], ["psapi"]),
    "CSF_winmm": ([], ["winmm"]),
    "CSF_shell32": ([], ["shell32"]),
}


def words(path):
    return path.read_text().split() if path.exists() else []


def main():
    src = Path(sys.argv[1])
    tks, todo = {}, list(ROOTS)
    while todo:
        tk = todo.pop()
        if tk in tks:
            continue
        ext = words(src / tk / "EXTERNLIB")
        tks[tk] = {"packages": words(src / tk / "PACKAGES"), "deps": [e for e in ext if e.startswith("TK")] + EXTRA_DEPS.get(tk, []),
                   "csf": [e for e in ext if e.startswith("CSF_")]}
        todo += tks[tk]["deps"]

    # Anubis deps must be acyclic; lld resolves archives in any order, so a
    # back edge can simply be dropped (its symbols still link).
    order, state = [], {}
    def visit(tk):
        state[tk] = 1
        for d in list(tks[tk]["deps"]):
            if state.get(d) == 1:
                tks[tk]["deps"].remove(d)
                tks[tk].setdefault("dropped", []).append(d)
            elif d not in state:
                visit(d)
        state[tk] = 2
        order.append(tk)
    for tk in sorted(tks):
        if tk not in state:
            visit(tk)

    out = ["# --- OpenCASCADE 7.9.3: generated by tools/anubis/occt_to_anubis.py, do not edit ---"]
    for tk in sorted(tks):
        info = tks[tk]
        srcs, c_srcs, dirs = [], [], []
        for pkg in info["packages"]:
            dirs.append(f"occt/{pkg}")
            for f in words(src / pkg / "FILES"):
                if f.endswith((".cxx", ".cpp")):  # .mm (Cocoa) is macOS-only
                    srcs.append(f"occt/{pkg}/{f}")
                elif f.endswith(".c"):
                    c_srcs.append(f"occt/{pkg}/{f}")
        if tk == "TKernel":
            # Standard_Version.hxx, which OCCT's CMake generates from
            # adm/templates/Standard_Version.hxx.in; checked in.
            dirs.append("occt_generated")
        linux = sorted({l for c in info["csf"] for l in CSF.get(c, ([], []))[0]})
        windows = sorted({l for c in info["csf"] for l in CSF.get(c, ([], []))[1]})
        q = lambda xs, ind: "".join(f'{ind}"{x}",\n' for x in xs)
        dropped = f"    # Cycle: also uses {', '.join(info['dropped'])} (lld needs no order).\n" if info.get("dropped") else ""
        deps = [":" + d for d in info["deps"]] + ([":rapidjson"] if "CSF_RapidJSON" in info["csf"] else [])
        if c_srcs:
            # A target compiles all its sources in one language, so the C files
            # (extern "C" in their headers) get a C library of their own.
            deps.append(f":{tk}_c")
            out.append(f'''cc_static_library(
    name = "{tk}_c",
    lang = "c",
    srcs = RelPaths([
{q(c_srcs, "        ")}    ]),
    private_include_dirs = RelPaths([
{q(dirs, "        ")}    ]),
    private_compiler_flags = [ "-w" ],
)''')
        out.append(f'''cc_static_library(
    name = "{tk}",
    lang = "cpp",
{dropped}    srcs = RelPaths([
{q(srcs, "        ")}    ]),
    deps = Targets([
{q(sorted(deps), "        ")}    ]),
    public_include_dirs = RelPaths([
{q(dirs, "        ")}    ]),
    public_libraries = select(
        (target_platform) => {{
            (windows) = [ {", ".join(f'"{l}"' for l in windows)} ],
            default = [ {", ".join(f'"{l}"' for l in linux)} ],
        }}
    ),
    private_compiler_flags = [ "-w", "-fexceptions", "-std=gnu++17" ],
    private_defines = [
        "HAVE_RAPIDJSON",
        "No_Exception",
        "OCC_CONVERT_SIGNALS",
        "OCCT_NO_PLUGINS",
    ] + select(
        (target_platform) => {{
            (windows) = [ "_CRT_SECURE_NO_WARNINGS", "_CRT_NONSTDC_NO_DEPRECATE", "_WIN32_WINNT=0x0601" ],
            default = [],
        }}
    ),
)''')
    print("\n\n".join(out))


main()
